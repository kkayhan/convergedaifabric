#!/usr/bin/env python3
"""Generate topology/aifabric-topo.yaml, the ONE NetworkTopology of the aifabric lab.

Look-alike of an AI factory's converged high-speed interconnect (HSI, rail-optimised GPU backend + frontend):
  spines   l2-1, l2-2                                  (role=spine)
  rails    l1-1..l1-4  GPU0..GPU3 of every GPU server  (role=leaf, stripe=gpu1, rail=N)
  non-gpu  l1-5, l1-6  storage island, dual-homed      (role=leaf, stripe=non-gpu)
All 8 switches: 7220 IXR-H5-64D, SR Linux 26.7.1, ONE aifabrics Backend over all of them, EVPN overlay
(owner 2026-10-27): stripe gpu1 = the rails (`gpu` until 2026-10-27), stripe non-gpu = l1-5/l1-6 (storage, CPU, management nodes; `frontend` until the owner
renamed it 2026-10-27),
stripe connector = the spines over all 84 ISLs. 2026-10-26 → 10-27 l1-5/l1-6 were their own Fabric
`frontend` (label fabric=frontend).
Switch labels = short `role` only (owner 2026-10-26, Q1 C); EDA's topology view tiers them through
the TopologyGrouping in grouping.yaml. `eda.nokia.com/security-profile: managed` stays (EDA-managed TLS).

Port plan (owner decisions R4-Q6/Q7/Q9, 2026-10-23):
  ISLs     14 native 800G per leaf: leaf e1-51..57 -> l2-1, e1-58..64 -> l2-2;
           spine port for leaf k = e1-((k-1)*7+1) .. e1-(k*7). Spine = LOCAL endpoint
           (the aifabrics stripe connector must own the local side, else the txn fails).
  GPU      server s rail r -> l1-r port e1-ceil(s/2), channel (s-1)%2+1 (2x400G breakout).
           PER-GPU TENANCY (owner 2026-10-26: tenants book GPUs, not servers; isolation per NIC;
           NVLink off): every GPU = its own sim "GPU VM" gpu-<s>-g<G> with ONE NIC eth1 = the GPU's
           ConnectX-8 on rail G+1 (as when tenant OpenShift workers run as VMs on the GPU blades, GPU + NIC
           passed through). The physical server = Interface label gpu-server only. Tenant = Interface
           label tenant=1|2; no label = free (unbooked: the Backend parks the port). Bookings = relabel.
  storage  dual-homed ESI-LAGs (one link, two `local` endpoints => lag-<link>-local):
           ces-1, axelera-1 = 2x400G on e1-1; mgmt cluster + cpu-1 = 4x200G on e1-11/e1-12.

NetworkTopology is a one-shot workflow and names its breakouts per topology
(local-<C>x<speed>-<i>), so every breakout lives in this one file.
Every server starts as network-multitool; the Kubernetes phase (P5) swaps the
k8s nodes to kindest/node by patching SimNode spec.containerImage.
"""
import pathlib

NS = "aifabric"
NODE_PROFILE = "srlinux-ghcr-26.7.1"
PLATFORM = "7220 IXR-H5-64D"
SERVER_IMAGE = "ghcr.io/srl-labs/network-multitool"

SPINES = ["l2-1", "l2-2"]
RAILS = ["l1-1", "l1-2", "l1-3", "l1-4"]
STORAGE = ["l1-5", "l1-6"]
LEAVES = RAILS + STORAGE
ISL_PER_SPINE = 7

# server -> initial booking of GPU0..GPU3 (= rails 1..4): tenant number or None = free
# (owner Q3 A 2026-10-26: one whole server, one split, free GPUs; every rail leaf carries both tenants)
GPU_SERVERS = {"gpu-1": (1, 1, 1, 1), "gpu-2": (1, 1, 2, 2), "gpu-3": (2, 2, None, None),
               "gpu-4": (2, 2, None, None)}

# storage-island hosts: name -> (template, port, channel, labels)
ISLAND = {
    "ces-1":     ("srv-400", 1, 1, {"server-role": "storage"}),
    "axelera-1": ("srv-400", 1, 2, {"server-role": "accelerator"}),
    "ocp-m1":    ("srv-200", 11, 1, {"server-role": "ocp-master"}),
    "ocp-m2":    ("srv-200", 11, 2, {"server-role": "ocp-master"}),
    "ocp-m3":    ("srv-200", 11, 3, {"server-role": "ocp-master"}),
    "ocp-s1":    ("srv-200", 11, 4, {"server-role": "ocp-services"}),
    "ocp-s2":    ("srv-200", 12, 1, {"server-role": "ocp-services"}),
    "ocp-s3":    ("srv-200", 12, 2, {"server-role": "ocp-services"}),
    "cpu-1":     ("srv-200", 12, 3, {"server-role": "cpu"}),     # shared CPU node, no tenant (owner Q1 B 2026-10-27)
}


def flow(d):
    """Render a flat dict as a YAML flow mapping."""
    parts = []
    for k, v in d.items():
        if isinstance(v, dict):
            v = flow(v)
        elif isinstance(v, str) and (v.isdigit() or " " in v or v == ""):
            v = f'"{v}"'
        parts.append(f"{k}: {v}")
    return "{ " + ", ".join(parts) + " }"


def main():
    out = []
    w = out.append
    w("# GENERATED by topology/gen-topology.py — edit the generator, not this file.")
    w("# aifabric lab: 2 spines + 4 rail leaves + 2 non-GPU leaves (7220 IXR-H5-64D, srl 26.7.1),")
    w("# 84 ISLs, 4 GPU servers x 4 rails = 16 single-NIC GPU VMs, 9 dual-homed storage-island hosts. One-shot NetworkTopology.")
    w("apiVersion: topologies.eda.nokia.com/v1")
    w("kind: NetworkTopology")
    w("metadata:")
    w("  name: aifabric")
    w(f"  namespace: {NS}")
    w("spec:")
    w("  operation: Create")
    w("  nodeTemplates:")
    for name, labels in [
        ("spine", {"role": "spine"}),
        ("leaf-rail", {"role": "leaf", "stripe": "gpu1"}),
        ("leaf-non-gpu", {"role": "leaf", "stripe": "non-gpu"}),
    ]:
        labels = {**labels, "eda.nokia.com/security-profile": "managed"}
        w(f"    - name: {name}")
        w(f"      nodeProfile: {NODE_PROFILE}")
        w(f"      platform: {PLATFORM}")
        w(f"      labels: {flow(labels)}")
    w("  nodes:")
    for s in SPINES:
        w(f"    - {{ name: {s}, template: spine }}")
    for i, l in enumerate(RAILS, 1):
        w(f"    - {{ name: {l}, template: leaf-rail, labels: {{ rail: \"{i}\" }} }}")
    for l in STORAGE:
        w(f"    - {{ name: {l}, template: leaf-non-gpu }}")

    w("  linkTemplates:")
    w("    - { name: isl, type: InterSwitch, labels: { role: interSwitch } }")
    for t in ("1", "2", None):                      # gpu-free: no tenant label = unbooked, parked port
        w(f"    - name: gpu-{'t' + t if t else 'free'}")
        w("      type: Edge")
        w("      encapType: Dot1q")
        w(f"      labels: {flow({'role': 'gpu', **({'tenant': t} if t else {})})}")
        w("      breakouts: [ { local: { channels: 2, speed: 400G } } ]")
    for name, ch, sp in (("srv-400", 2, "400G"), ("srv-200", 4, "200G")):
        w(f"    - name: {name}")
        w("      type: Edge")
        w("      encapType: Dot1q")
        w("      labels: { role: server }")
        w(f"      breakouts: [ {{ local: {{ channels: {ch}, speed: {sp} }} }} ]")

    w("  links:")
    w("    # ISLs: spine = local endpoint")
    for k, leaf in enumerate(LEAVES, 1):
        for si, spine in enumerate(SPINES):
            for j in range(ISL_PER_SPINE):
                sp_port = (k - 1) * ISL_PER_SPINE + 1 + j
                lf_port = 51 + si * ISL_PER_SPINE + j
                w(f"    - {{ name: {spine}-e{sp_port}-{leaf}-e{lf_port}, template: isl, endpoints: "
                  f"[ {{ local: {{ node: {spine}, interface: ethernet-1-{sp_port} }}, "
                  f"remote: {{ node: {leaf}, interface: ethernet-1-{lf_port} }} }} ] }}")
    w("    # GPU rails: server s rail r -> l1-r e1-ceil(s/2) channel (s-1)%2+1; GPU VM gpu-<s>-g<r-1> eth1")
    topo_map, gpu_vms = [], []
    for s_idx, (srv, booking) in enumerate(GPU_SERVERS.items(), 1):
        port, ch = (s_idx + 1) // 2, (s_idx - 1) % 2 + 1
        for r, leaf in enumerate(RAILS, 1):
            ifname, vm, t = f"ethernet-1-{port}-{ch}", f"{srv}-g{r - 1}", booking[r - 1]
            labels = {"gpu-server": srv, "rail": str(r)}
            w(f"    - {{ name: {vm}, template: gpu-{'t' + str(t) if t else 'free'}, labels: {flow(labels)}, endpoints: "
              f"[ {{ local: {{ node: {leaf}, interface: {ifname} }} }} ] }}")
            topo_map.append((leaf, ifname, vm, "eth1"))
            gpu_vms.append(vm)
    w("    # storage island: all-active ESI-LAG to l1-5 + l1-6")
    for host, (tmpl, port, ch, labels) in ISLAND.items():
        ifname = f"ethernet-1-{port}-{ch}"
        labels = {"server": host, **labels}
        w(f"    - {{ name: {host}, template: {tmpl}, labels: {flow(labels)}, endpoints: "
          f"[ {{ local: {{ node: {STORAGE[0]}, interface: {ifname} }} }}, "
          f"{{ local: {{ node: {STORAGE[1]}, interface: {ifname} }} }} ] }}")
        topo_map.append((STORAGE[0], ifname, host, "eth1"))
        topo_map.append((STORAGE[1], ifname, host, "eth2"))

    w("  simulation:")
    w("    simNodeTemplates:")
    w(f"      - {{ name: server, type: Linux, image: {SERVER_IMAGE} }}")
    w("    simNodes:")
    for srv in gpu_vms + list(ISLAND):
        w(f"      - {{ name: {srv}, template: server }}")
    w("    # explicit sim wiring (never mix with wildcards)")
    w("    topologies:")
    for leaf, ifname, srv, eth in topo_map:
        w(f"      - {{ node: {leaf}, interface: {ifname}, simNode: {srv}, simNodeInterface: {eth} }}")

    dst = pathlib.Path(__file__).with_name("aifabric-topo.yaml")
    dst.write_text("\n".join(out) + "\n")
    print(f"wrote {dst} ({len(out)} lines)")


if __name__ == "__main__":
    main()
